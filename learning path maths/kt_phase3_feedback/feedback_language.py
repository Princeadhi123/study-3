"""Shared plain-language guidance for generated assessment feedback."""
MATH_NOTATION_INSTRUCTIONS = (
    "\nMathematical notation and operand fidelity: the Unicode fraction "
    "slash (⁄, U+2044) means division, exactly like /. Read every digit "
    "on each side literally as one numerator and one denominator. "
    "3⁄6 means 3/6, not 3 4/5 or 3/4; 10⁄1 means 10/1, not 10 1/4; "
    "1⁄2 means 1/2, not 1 1/2 or 1/4; 2⁄3 means 2/3, not 2 1/3. "
    "These are notation checks, not additional exercises to assign. "
    "Never invent digits, superscripts, denominators or whole-number parts. "
    "Before solving a supplied worked question, identify its exact operands "
    "and operation; begin the teaching steps by stating those operands "
    "faithfully in plain text. A fraction whose numerator is smaller than "
    "its positive denominator is proper: 3/6 is proper, while 10/1 is "
    "improper. Neither is a mixed number. Only introduce mixed-number "
    "conversion when a whole-number part and a separate fractional part "
    "are explicitly present in the supplied question. "
    "For fraction multiplication, multiply the original numerators and "
    "original denominators, then check each arithmetic equality and any "
    "simplification. Equivalent forms may match an unsimplified answer "
    "option; simplifying is not a prerequisite for comparing their values. "
    "For example, 7/2 = 3 1/2, never 3/2. Equivalent rewrites preserve "
    "value; multiplying two fractions forms their product, not an operation "
    "that leaves each original fraction's value unchanged. "
    "Before claiming an answer-key discrepancy, re-read the original "
    "operands, recompute without changing them, and compare equivalent "
    "values rather than spellings. Only a discrepancy that survives these "
    "checks warrants teacher checking; never invent a matching option. "
    "Write generated mathematics as readable plain text, such as 2/3, "
    "(2 × 4)/(3 × 5), and 1 2/3 for a mixed number. Use parentheses to "
    "preserve grouping. Do not use LaTeX commands or math delimiters in "
    "sections, steps, or reasoning questions. Preserve copied identifiers "
    "and the supplied question and answer records exactly. Do not reproduce "
    "these notation examples in narrative-only or midpoint feedback."
)
ASSESSMENT_FACT_INSTRUCTIONS = (
    "\nEvidence reconciliation before returning: ground each performance "
    "claim in one matching supplied evidence row at the same topic or "
    "subtopic level. Copy that row's correct, incorrect and out_of counts "
    "together; never transfer a parent topic's score or denominator to a "
    "child subtopic. Child counts are already included in the parent, not "
    "extra successes. Keep prime recognition separate from divisor "
    "identification, unlike terms separate from combining coefficients, "
    "and fractional quantities separate from fraction products. If an "
    "exact subtopic count is unavailable, omit it rather than infer it. "
    "Use 'all correct', 'every answer correct', 'none incorrect', "
    "'complete accuracy' or equivalent success wording only when "
    "correct equals out_of and incorrect is zero for "
    "that exact group. For 7 correct out of 10, say '7 of 10', never "
    "'all seven questions'. Verify these conditions even when the number "
    "is spelled out or no number appears in the sentence. Describe correct "
    "answers, not demonstrated understanding or a solid grasp of a skill. "
    "Incorrect completed answers are not unanswered, missing or skipped. "
    "Do not invent question examples or claim a specific item was correct "
    "unless its exact record is supplied and marked correct. Do not derive "
    "performance percentages. Preserve supplied tie qualifications without "
    "inventing ties or describing a selected subset as the only errors. "
    "Translate labels into everyday English without exposing field names "
    "such as fraction_product. Silently check every numerical and 'all "
    "correct' claim across all sections for consistency; omit unsupported "
    "claims instead of filling gaps. Return no report of this check."
)
