"""Shared plain-language guidance for generated assessment feedback."""
_MATH_TEXT_FIELDS = frozenset({
    "prompt", "question", "text", "options", "selected_answer", "correct_answer"})


def provider_math_context(value):
    """Copy a provider context, normalizing fraction slashes only in math text."""
    def math_text(item):
        if isinstance(item, str):
            return item.replace("⁄", "/")
        if isinstance(item, list):
            return [math_text(part) for part in item]
        return provider_math_context(item)

    if isinstance(value, dict):
        return {key: math_text(item) if key in _MATH_TEXT_FIELDS
                else provider_math_context(item) for key, item in value.items()}
    if isinstance(value, list):
        return [provider_math_context(item) for item in value]
    return value


